/** Map Transfermarkt's detailed position ("Centre-Back") to a group key. */
export function positionGroup(pos = '') {
  const p = pos.toLowerCase();
  if (p.includes('goalkeeper')) return 'Goalkeeper';  if (p.includes('back') || p.includes('defen')) return 'Defender';
  if (p.includes('midfield')) return 'Midfield';
  if (p.includes('wing') || p.includes('forward') || p.includes('striker') || p.includes('attack')) return 'Attack';
  return '';
}
